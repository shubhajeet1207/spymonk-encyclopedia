import assert from 'node:assert/strict'
import { test } from 'node:test'

import { privacySummary } from './privacy.js'

test('pre-auth copy does not assume local storage', () => {
  const copy = privacySummary(null)
  assert.match(copy, /after API access/i)
  assert.doesNotMatch(copy, /this machine/i)
})

test('local Chroma and local embeddings are identified as API-host processing', () => {
  const copy = privacySummary({ vector_store_provider: 'chroma-local', embedding_provider: 'huggingface' })
  assert.match(copy, /API host’s disk/)
  assert.match(copy, /Embeddings are generated by the API host/)
  assert.doesNotMatch(copy, /Chroma Cloud/)
})

test('cloud Chroma and external embeddings disclose both external flows', () => {
  const copy = privacySummary({ vector_store_provider: 'chroma-cloud', embedding_provider: 'openai' })
  assert.match(copy, /Chroma Cloud/)
  assert.match(copy, /external embedding provider/)
  assert.match(copy, /PDFs and source snapshots are stored on the API host/)
})
