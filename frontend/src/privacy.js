export function privacySummary(status) {
  if (!status) return 'Storage and processing details appear after API access is confirmed.'
  const storage = status.vector_store_provider === 'chroma-cloud'
    ? 'PDFs and source snapshots are stored on the API host; the searchable vector index is in Chroma Cloud.'
    : 'PDFs, source snapshots, and the searchable vector index are stored on the API host’s disk.'
  const embeddings = status.embedding_provider === 'huggingface'
    ? 'Embeddings are generated by the API host.'
    : 'Relevant text and queries are sent to the configured external embedding provider.'
  return `${storage} ${embeddings} Research may also use configured search and LLM services.`
}
